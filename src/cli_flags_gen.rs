//! One-off: writes the engine's CLI flag table (`qsmxt_engine::schema::cli_flags`) from today's
//! `PipelineArgs`. Run with `cargo test --bin qsmxt cli_flags_gen -- --ignored`.

use clap::{Args, Command};

fn q(s: &str) -> String {
    format!("{s:?}")
}

fn list(items: impl IntoIterator<Item = String>) -> String {
    let v: Vec<String> = items.into_iter().collect();
    format!("&[{}]", v.join(", "))
}

#[test]
#[ignore = "one-off generator"]
fn cli_flags_gen() {
    let mut cmd = crate::cli::PipelineArgs::augment_args(Command::new("t"));
    cmd.build();
    let mut out = String::from("// @generated by src/cli_flags_gen.rs from PipelineArgs, then maintained by hand.\n\nuse super::cli::{Flag, FlagAction::*, FlagValue as V};\n\n/// `qsmxt run`'s settings flags, in the order `--help` lists them.\npub static PIPELINE_FLAGS: &[Flag] = &[\n");
    for arg in cmd.get_arguments().filter(|a| a.get_id() != "help") {
        let debug = format!("{arg:?}");
        let field = |name: &str| -> Vec<String> {
            let Some(i) = debug.find(&format!("{name}: [")) else { return vec![] };
            let rest = &debug[i + name.len() + 3..];
            let body = &rest[..rest.find(']').unwrap()];
            body.split('"').skip(1).step_by(2).map(String::from).collect()
        };
        let requires: Vec<String> = field("requires").into_iter().map(|s| q(&s)).collect();
        let default_missing: Vec<String> = field("default_missing_vals").into_iter().map(|s| q(&s)).collect();
        let range = arg.get_num_args().unwrap();
        let max = if range.max_values() == usize::MAX { "usize::MAX".to_string() } else { range.max_values().to_string() };
        let possible = arg.get_possible_values();
        let values = possible.iter().map(|p| {
            let aliases: Vec<String> = p.get_name_and_aliases().skip(1).map(q).collect();
            format!("V {{ name: {}, help: {}, hide: {}, aliases: {} }}", q(p.get_name()),
                    p.get_help().map_or("None".into(), |h| format!("Some({})", q(&h.to_string()))), p.is_hide_set(), list(aliases))
        });
        let conflicts: Vec<String> = cmd.get_arg_conflicts_with(arg).iter().map(|a| q(a.get_id().as_str())).collect();
        let mut flags = Vec::new();
        for (set, name) in [(arg.is_hide_set(), "hide"), (arg.is_allow_hyphen_values_set(), "allow_hyphen_values"),
                            (arg.is_allow_negative_numbers_set(), "allow_negative_numbers"),
                            (arg.is_hide_possible_values_set(), "hide_possible_values"),
                            (arg.is_hide_default_value_set(), "hide_default_value"), (arg.is_require_equals_set(), "require_equals"),
                            (arg.is_required_set(), "required"), (arg.is_ignore_case_set(), "ignore_case")] {
            if set {
                flags.push(q(name));
            }
        }
        assert!(arg.get_short().is_none() && arg.get_value_delimiter().is_none(), "{}", arg.get_id());
        out.push_str(&format!(
            "    Flag {{ id: {}, long: {}, aliases: {}, visible_aliases: {}, value_names: {}, num_args: ({}, {max}), action: {:?},\n           help: {}, long_help: {},\n           values: {}, defaults: {}, default_missing: {}, conflicts: {}, requires: {}, attrs: {} }},\n",
            q(arg.get_id().as_str()), q(arg.get_long().unwrap()),
            list(arg.get_aliases().unwrap_or_default().into_iter().map(q)),
            list(arg.get_visible_aliases().unwrap_or_default().into_iter().map(q)),
            list(arg.get_value_names().unwrap_or_default().iter().map(|n| q(n.as_str()))),
            range.min_values(), arg.get_action(),
            arg.get_help().map_or("None".into(), |h| format!("Some({})", q(&h.to_string()))),
            arg.get_long_help().map_or("None".into(), |h| format!("Some({})", q(&h.to_string()))),
            list(values), list(arg.get_default_values().iter().map(|d| q(&d.to_string_lossy()))),
            list(default_missing), list(conflicts), list(requires), list(flags)));
    }
    out.push_str("];\n");
    std::fs::write(concat!(env!("CARGO_MANIFEST_DIR"), "/crates/qsmxt-engine/src/schema/cli_flags.rs"), out).unwrap();
}
