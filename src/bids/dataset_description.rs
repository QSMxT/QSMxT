//! Writes the BIDS `dataset_description.json` for the qsmxt derivatives dataset.
//!
//! Every derived BIDS dataset MUST contain a `dataset_description.json` at its
//! top level (`derivatives/qsmxt/dataset_description.json`), with
//! `DatasetType: "derivative"` and a `GeneratedBy` array. The `Name` of the
//! first `GeneratedBy` object MUST be a substring of the derivative directory
//! name — here both are `qsmxt`.

use std::path::Path;

use serde::Serialize;

const BIDS_VERSION: &str = "1.10.0";
const CODE_URL: &str = "https://github.com/QSMxT/qsmxt";

#[derive(Serialize)]
struct GeneratedBy {
    #[serde(rename = "Name")]
    name: String,
    #[serde(rename = "Version")]
    version: String,
    #[serde(rename = "CodeURL")]
    code_url: String,
}

#[derive(Serialize)]
struct SourceDataset {
    #[serde(rename = "URL")]
    url: String,
}

#[derive(Serialize)]
struct DatasetDescription {
    #[serde(rename = "Name")]
    name: String,
    #[serde(rename = "BIDSVersion")]
    bids_version: String,
    #[serde(rename = "DatasetType")]
    dataset_type: String,
    #[serde(rename = "GeneratedBy")]
    generated_by: Vec<GeneratedBy>,
    #[serde(rename = "SourceDatasets", skip_serializing_if = "Vec::is_empty")]
    source_datasets: Vec<SourceDataset>,
}

fn build(source_bids_dir: &Path) -> DatasetDescription {
    // Record the raw dataset this was derived from as a file:// URI when the
    // path can be resolved to an absolute location; otherwise omit it.
    let source_datasets = std::fs::canonicalize(source_bids_dir)
        .ok()
        .map(|p| {
            vec![SourceDataset {
                url: format!("file://{}", p.display()),
            }]
        })
        .unwrap_or_default();

    DatasetDescription {
        name: "QSMxT QSM outputs".to_string(),
        bids_version: BIDS_VERSION.to_string(),
        dataset_type: "derivative".to_string(),
        generated_by: vec![GeneratedBy {
            name: "qsmxt".to_string(),
            version: env!("CARGO_PKG_VERSION").to_string(),
            code_url: CODE_URL.to_string(),
        }],
        source_datasets,
    }
}

/// Write `dataset_description.json` into the derivatives directory.
pub fn write(derivatives_dir: &Path, source_bids_dir: &Path) -> crate::Result<()> {
    let desc = build(source_bids_dir);
    let json = serde_json::to_string_pretty(&desc).map_err(|e| {
        crate::error::QsmxtError::Config(format!("Failed to serialize dataset_description.json: {}", e))
    })?;
    std::fs::write(derivatives_dir.join("dataset_description.json"), json)?;
    Ok(())
}

/// `.bidsignore` contents: non-BIDS pipeline artefacts and the BEP028 `prov/`
/// records (BIDS-Prov is not yet part of the released BIDS schema, so the
/// validator flags it unless ignored).
// Note: directory entries use the bare name (no trailing slash); the BIDS
// validator's ignore matcher does not treat the directory node itself as
// ignored when a `dir/` or `dir/**` form is used.
const BIDSIGNORE: &str = "\
# qsmxt pipeline artefacts (not BIDS data files)
*.log
methods.md
pipeline_config.toml
workflow
# BEP028 (BIDS-Prov) records — not yet in the released BIDS schema
prov
";

/// Write a `.bidsignore` so the derivatives dataset validates cleanly against
/// the current BIDS validator.
pub fn write_bidsignore(derivatives_dir: &Path) -> crate::Result<()> {
    std::fs::write(derivatives_dir.join(".bidsignore"), BIDSIGNORE)?;
    Ok(())
}

const README: &str = "\
# QSMxT QSM outputs

This is a BIDS-Derivatives dataset generated by [qsmxt](https://github.com/QSMxT/qsmxt).

It contains Quantitative Susceptibility Mapping (QSM) outputs and related maps
(`Chimap`, `mask`, `part-mag_T2starw`, and optionally `swi`/`minIP` and
`T2starmap`/`R2starmap`) derived from a raw BIDS dataset.

- `dataset_description.json` — dataset-level provenance (`GeneratedBy`, `SourceDatasets`).
- `methods.md` — a human-readable description of the processing pipeline.
- `prov/` — BEP028 (BIDS-Prov) provenance records: one Activity per pipeline
  stage, with Entity/Agent/Environment records. Each output NIfTI also carries a
  `GeneratedBy` reference in its JSON sidecar.
- `workflow/` — intermediate files and per-step provenance (not BIDS data).
";

/// Write a minimal `README` (recommended for every BIDS dataset).
pub fn write_readme(derivatives_dir: &Path) -> crate::Result<()> {
    std::fs::write(derivatives_dir.join("README"), README)?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_first_generatedby_name_is_substring_of_dir() {
        // BIDS rule: the first GeneratedBy.Name must be a substring of the
        // derivative directory name ("qsmxt").
        let desc = build(Path::new("/nonexistent"));
        assert!("qsmxt".contains(&desc.generated_by[0].name));
    }

    #[test]
    fn test_derivative_dataset_type_and_required_fields() {
        let desc = build(Path::new("/nonexistent"));
        assert_eq!(desc.dataset_type, "derivative");
        assert!(!desc.generated_by.is_empty());
        assert_eq!(desc.generated_by[0].version, env!("CARGO_PKG_VERSION"));
    }

    #[test]
    fn test_unresolvable_source_is_omitted() {
        let desc = build(Path::new("/nonexistent/path/xyz"));
        assert!(desc.source_datasets.is_empty());
    }

    #[test]
    fn test_write_produces_valid_json() {
        let dir = tempfile::tempdir().unwrap();
        write(dir.path(), Path::new("/nonexistent")).unwrap();
        let text = std::fs::read_to_string(dir.path().join("dataset_description.json")).unwrap();
        let value: serde_json::Value = serde_json::from_str(&text).unwrap();
        assert_eq!(value["DatasetType"], "derivative");
        assert_eq!(value["GeneratedBy"][0]["Name"], "qsmxt");
    }
}
